// Writes the category SQL from src/lib/category-catalog.ts, so the catalog the
// tests check is the one the database gets:
//   supabase/seed_categories.sql                       — a fresh database
//   supabase/migrations/2026-10-06-category-catalog.sql — the live one
// Usage: npm run categories:sql            write both files
//        npm run categories:sql -- --check  fail if either is stale (npm test runs this)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CATEGORY_MERGES,
  CATEGORY_RENAMES,
  SYSTEM_CATEGORIES,
} from '../src/lib/category-catalog.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const q = (s) => (s == null ? 'null' : `'${String(s).replaceAll("'", "''")}'`);
const kindOf = (name) => SYSTEM_CATEGORIES.find((c) => c.name === name)?.kind;

const row = (c) => `${q(c.name)}, ${q(c.kind)}, ${q(c.scope)}, ${c.tenantOnly ? 'true' : 'false'}, ${q(c.description)}`;
const values = SYSTEM_CATEGORIES.map((c) => `  (${row(c)})`).join(',\n');
const seedValues = SYSTEM_CATEGORIES.map((c) => `  (${row(c)}, true)`).join(',\n');

const header = `-- GENERATED by scripts/build-category-sql.mjs from src/lib/category-catalog.ts.
-- Edit the catalog and re-run the script; do not edit this file by hand.`;

const seed = `${header}
-- System categories (is_system = true, user_id null) are visible to every user and
-- cannot be deleted in-app. Run after schema.sql.
insert into categories (name, kind, scope, tenant_only, description, is_system) values
${seedValues};
`;

const renames = Object.entries(CATEGORY_RENAMES)
  .map(
    ([from, to]) =>
      `update categories set name = ${q(to)} where is_system and name = ${q(from)} and kind = ${q(kindOf(to))}\n` +
      `  and not exists (select 1 from categories t where t.is_system and t.name = ${q(to)} and t.kind = ${q(kindOf(to))});`
  )
  .join('\n');

const merges = Object.entries(CATEGORY_MERGES)
  .map(([from, to]) => {
    const kind = q(kindOf(to));
    const src = `(select id from categories where is_system and name = ${q(from)} and kind = ${kind})`;
    const dst = `(select id from categories where is_system and name = ${q(to)} and kind = ${kind})`;
    return [
      `-- ${from} → ${to}`,
      ...['expenses', 'income', 'recurring_rules'].map(
        (t) => `update ${t} set category_id = ${dst} where category_id = ${src};`
      ),
      `delete from categories where is_system and name = ${q(from)} and kind = ${kind};`,
    ].join('\n');
  })
  .join('\n\n');

const migration = `${header}
--
-- Brings the system categories in line with the catalog: mortgage options for
-- every way people pay (with escrow, without, split, escrow or PMI on its own),
-- property tax as one bill or as separate school / county / city-town bills,
-- trims categories almost nobody used, and adds a one-line description where a
-- name alone could be misread. Renames keep their rows, so entries stay put;
-- merged rows move their entries (and recurring rules) to the survivor first.
-- Idempotent: safe to run twice. User-created categories are never touched.

begin;

alter table categories add column if not exists description text;

-- 1. Renames (same row, new name).
${renames}

-- 2. Merges (move entries and rules, then drop the old row). Make sure each
--    target exists first; usually it already does, or a rename above made it.
insert into categories (name, kind, scope, is_system)
select v.name, v.kind, v.scope, true
  from (values
${SYSTEM_CATEGORIES.filter((c) => Object.values(CATEGORY_MERGES).includes(c.name))
  .map((c) => `    (${q(c.name)}, ${q(c.kind)}, ${q(c.scope)})`)
  .join(',\n')}
  ) as v(name, kind, scope)
 where not exists (select 1 from categories c where c.is_system and c.name = v.name and c.kind = v.kind);

${merges}

-- 3. Every catalog row: update in place, or insert when new.
create temporary table catalog (name text, kind text, scope text, tenant_only boolean, description text) on commit drop;
insert into catalog values
${values};

update categories c
   set scope = k.scope, tenant_only = k.tenant_only, description = k.description
  from catalog k
 where c.is_system and c.name = k.name and c.kind = k.kind;

insert into categories (name, kind, scope, tenant_only, description, is_system)
select k.name, k.kind, k.scope, k.tenant_only, k.description, true
  from catalog k
 where not exists (select 1 from categories c where c.is_system and c.name = k.name and c.kind = k.kind);

-- 4. Nothing outside the catalog may survive as a system category.
do $$
declare stray text;
begin
  select string_agg(c.name, ', ') into stray
    from categories c
   where c.is_system and not exists (select 1 from catalog k where k.name = c.name and k.kind = c.kind);
  if stray is not null then
    raise exception 'system categories missing from the catalog: %', stray;
  end if;
end $$;

commit;
`;

const outputs = {
  'supabase/seed_categories.sql': seed,
  'supabase/migrations/2026-10-06-category-catalog.sql': migration,
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([path, text]) => readFileSync(join(root, path), 'utf8') !== text);
  if (stale.length > 0) {
    console.error(`Out of date with src/lib/category-catalog.ts: ${stale.map(([p]) => p).join(', ')}. Run npm run categories:sql.`);
    process.exit(1);
  }
  console.log('category SQL matches the catalog');
} else {
  for (const [path, text] of Object.entries(outputs)) writeFileSync(join(root, path), text);
  console.log(`wrote ${SYSTEM_CATEGORIES.length} categories`);
}
